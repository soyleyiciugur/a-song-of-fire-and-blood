const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module=require('node:module');const path=require('node:path');const resolve=Module._resolveFilename;
Module._resolveFilename=function(request,...args){return resolve.call(this,request.startsWith('@/')?path.join(process.cwd(),request.slice(2)):request,...args)};
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020,esModuleInterop:true}}).outputText,filename);
const {createGame,getMaximumHealth,getMilitaryPower,getPoliticalPower,applyAction} = require('../lib/the-great-game/engine.ts');
const {getGameCard}=require('../lib/the-great-game/cards.ts');
const {getPlacementPreview}=require('../lib/the-great-game/placement-preview.ts');
const {ArtworkMapSchema}=require('../lib/the-great-game/artwork.ts');
const unit=(id,cardId)=>({instanceId:id,cardId,ownerId:'player1',currentHealth:getGameCard(cardId).health,bonusHealth:0,exhausted:false,deployedThisTurn:false,grounded:false,attachedArtifactId:null,modifiers:[],counters:{},flags:{}});
const state=createGame();state.phase='playing';state.activePlayerId='player1';state.pendingEffect=null;state.players.player1.command=10;
state.players.player1.board=[unit('left','renrose-tyrell'),unit('middle','leo-tyrell'),unit('right','naela-targaryen')];
state.players.player1.hand=[{instanceId:'aura',cardId:'saathos-maris',costModifiers:[]}];
const before=JSON.stringify(state);
const preview=getPlacementPreview(state,'aura',1);
assert(preview);assert.equal(JSON.stringify(state),before);
assert.equal(getMaximumHealth(preview,preview.players.player1.board[0]),getMaximumHealth(state,state.players.player1.board[0])+1);
assert.equal(preview.players.player1.board[0].currentHealth,state.players.player1.board[0].currentHealth+1);
const moved=getPlacementPreview(state,'aura',3);
assert.equal(moved.players.player1.board[0].currentHealth,state.players.player1.board[0].currentHealth);
assert.equal(moved.players.player1.board[2].currentHealth,state.players.player1.board[2].currentHealth+1);
assert.equal(JSON.stringify(state),before);
// The held card receives both neighbors' auras, and insertion breaks their old adjacency.
state.players.player1.board=[unit('champion','crownlands-champion'),unit('counselor','grand-counselor')];
const original=JSON.stringify(state);
const between=getPlacementPreview(state,'aura',1);
assert(between);
const held=between.players.player1.board[1];
const heldCard=getGameCard(held.cardId);
assert.equal(getMilitaryPower(between,held),heldCard.strength+1);
assert.equal(getPoliticalPower(between,held),heldCard.influence+1);
assert.equal(getMaximumHealth(between,held),heldCard.health+2);
assert.equal(getPoliticalPower(between,between.players.player1.board[0]),getPoliticalPower(state,state.players.player1.board[0])-1);
assert.equal(getMilitaryPower(between,between.players.player1.board[2]),getMilitaryPower(state,state.players.player1.board[1])-1);
const edge=getPlacementPreview(state,'aura',0);
assert(edge);
assert.equal(getPoliticalPower(edge,edge.players.player1.board[0]),heldCard.influence);
assert.equal(getMaximumHealth(edge,edge.players.player1.board[0]),heldCard.health+1);
assert.equal(JSON.stringify(state),original);
const dropped=applyAction(state,{type:'play-card',handInstanceId:'aura',boardIndex:1});
assert(dropped.ok);
assert.deepEqual(dropped.state.players.player1.board,between.players.player1.board);
assert(!ArtworkMapSchema.safeParse({'renrose-tyrell':{x:200,y:0,zoom:1}}).success);
assert(!ArtworkMapSchema.safeParse({'bad-card':{x:50,y:0,zoom:1}}).success);
assert(ArtworkMapSchema.safeParse({'renrose-tyrell':{x:50,y:20,zoom:1.4}}).success);
console.log('Placement preview is immutable, follows neighbors, updates Health; artwork bounds and card IDs validated.');
