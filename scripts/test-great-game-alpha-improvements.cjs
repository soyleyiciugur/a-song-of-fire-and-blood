require('./test-great-game-decks.cjs');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const { createGame, applyAction } = require('../lib/the-great-game/engine.ts');
const { createTestDeck } = require('../lib/the-great-game/deck.ts');
const { deckHealth } = require('../lib/the-great-game/deck-health.ts');
const { findGameCard } = require('../lib/the-great-game/cards.ts');
const { tableActionStatus } = require('../lib/the-great-game/action-status.ts');
const { CONTEXTUAL_RULES } = require('../lib/the-great-game/contextual-rules.ts');
const { seatPresence } = require('../lib/the-great-game/table-tempo.ts');
const { gameTurnLabel, gameTurnNumber } = require('../lib/the-great-game/turn-labels.ts');

const testDeck = createTestDeck();
const counts = {};
for (const id of testDeck) counts[id] = (counts[id] || 0) + 1;
const health = deckHealth({ cards: counts });
assert.equal(health.validation.valid, true);
assert.equal(health.count, 30);
assert.equal(health.missing, 0);
assert.equal(health.unknown, 0);
assert.equal(Object.values(health.types).reduce((a, b) => a + b, 0), 30);
assert.equal(health.curve.reduce((a, b) => a + b, 0), 30);
assert(health.averageCommand > 0);
const incomplete = deckHealth({ cards: { [testDeck[0]]: 1, 'unknown-card': 1 } });
assert.equal(incomplete.validation.valid, false);
assert.equal(incomplete.missing, 28);
assert.equal(incomplete.unknown, 1);
assert.equal(incomplete.types[findGameCard(testDeck[0]).cardType], 1);
const invalid = deckHealth({cards:{[testDeck[0]]:31}});
assert.equal(invalid.validation.valid, false);
assert.equal(invalid.invalidEntries, 1);

assert(CONTEXTUAL_RULES.length >= 7);
for (const rule of CONTEXTUAL_RULES) for (const id of rule.cards) assert(findGameCard(id), `${rule.id}: ${id} must be a canonical game card`);
const review = CONTEXTUAL_RULES.filter(rule => rule.review).map(rule => rule.id);
assert(review.includes('traps'), 'Traps are not an implemented mechanic');
assert(review.includes('harrenhal'), 'Unresolved tie behavior is flagged for review');

let state = createGame();
assert.equal(gameTurnLabel(0), 'Opening');
assert.equal(tableActionStatus(state, 'player1').label, 'Choose your opening hand');
state = applyAction(state, { type: 'mulligan', replaceHandInstanceIds: [] }).state;
assert.equal(tableActionStatus(state, 'player1').label, 'Waiting for opponent');
state = applyAction(state, { type: 'mulligan', replaceHandInstanceIds: [] }).state;
assert.equal(state.turnNumber, 1);
assert.equal(gameTurnNumber(state.turnNumber), 1);
assert.equal(tableActionStatus(state, 'player1').label, 'Your action');
assert.equal(tableActionStatus(state, 'player2').label, 'Waiting for opponent');
assert.equal(tableActionStatus(state, 'player1', { selection: true }).label, 'Choose / confirm action');
assert.equal(tableActionStatus(state, 'player1', { sending: true }).label, 'Submitting action');
const pending = structuredClone(state);
pending.pendingEffect = { id:'check', controllerId:'player2', sourceUnitInstanceId:null, abilityId:'iron-wrath' };
assert.equal(tableActionStatus(pending, 'player2').label, 'Resolve effect');
assert.equal(tableActionStatus(pending, 'player1').label, 'Waiting for effect');
state = applyAction(state, { type: 'end-turn' }).state;
assert.equal(state.turnNumber, 2);
assert.equal(gameTurnLabel(state.turnNumber), 'Round 1');
state = applyAction(state, { type: 'end-turn' }).state;
assert.equal(state.turnNumber, 3);
assert.equal(gameTurnLabel(state.turnNumber), 'Round 2');
assert.equal(seatPresence([]), 'missing');
assert.equal(seatPresence([{away:true}]), 'away');
assert.equal(seatPresence([{},{}]), 'missing');
assert.equal(seatPresence([{away:true},{away:false}]), 'here');
const migration = fs.readFileSync('supabase/migrations/20261009200000_great_game_alpha_season.sql','utf8');
assert.match(migration, /insert into public\.great_game_seasons/);
assert.match(migration, /'beta','Beta','The Gathering Storm','planned'/);
assert.match(migration, /where match_type='ranked'/);
assert.match(migration, /create unique index great_game_one_active_season/);
assert.match(migration, /create trigger great_game_assign_season/);
assert.match(migration, /create trigger great_game_result_season/);
assert.match(migration, /check\(\(match_type='ranked' and season_id is not null\)/);
assert(!/set rating_after|update public\.great_game_ratings/.test(migration), 'The season migration must not re-score past matches');
console.log('PASS contextual card references, real deck diagnostics, active/target/wait states, turn semantics, AFK presence and static season schema checks');
