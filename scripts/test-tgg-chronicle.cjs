const assert = require('node:assert/strict');
const fs = require('node:fs');
const ts = require('typescript');
const Module = require('node:module');
const path = require('node:path');
const resolve = Module._resolveFilename;
Module._resolveFilename = function(request, ...args) { return resolve.call(this, request.startsWith('@/') ? path.join(process.cwd(), request.slice(2)) : request, ...args); };
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {compilerOptions: {module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, esModuleInterop: true}}).outputText, filename);
const {createGame, applyAction, getMilitaryPower} = require('../lib/the-great-game/engine.ts');
const {getGameCard} = require('../lib/the-great-game/cards.ts');
const {buildChronicle, formatChronicleEntry} = require('../lib/the-great-game/chronicle.ts');
const {projectGameStateForPlayer} = require('../lib/the-great-game/online.ts');
const {resolveChronicleEntity,chronicleUnitStats} = require('../lib/the-great-game/chronicle-entity.ts');
const unit = (id, cardId, ownerId = 'player1') => ({instanceId:id, cardId, ownerId, currentHealth:getGameCard(cardId).health, bonusHealth:0, exhausted:false, deployedThisTurn:false, grounded:false, attachedArtifactId:null, modifiers:[], counters:{}, flags:{}});
const state = createGame();
state.phase='playing'; state.turnNumber=7; state.activePlayerId='player1'; state.activeLocation=null; state.pendingEffect=null; state.log=[];
state.players.player1.command=10; state.players.player1.board=[unit('ally','leo-tyrell')]; state.players.player2.board=[];
state.players.player1.hand=[{instanceId:'play',cardId:'crownlands-champion',costModifiers:[]}];
const original=JSON.stringify(state);
const played=applyAction(state,{type:'play-card',handInstanceId:'play',boardIndex:0});
assert(played.ok,played.error); assert.equal(JSON.stringify(state),original);
const events=buildChronicle(played.state.log,'player1');
assert.equal(events.length,1); assert.equal(events[0].title,'Crownlands Champion');
assert.equal(events[0].turnOwnerId,'player1');
const buff=events[0].changes.find(change=>change.instanceId==='ally'&&change.stat==='Strength');
assert.equal(buff.before,getMilitaryPower(state,state.players.player1.board[0])); assert.equal(buff.after,buff.before+1);
assert(events[0].changes.some(change=>change.stat==='Command'&&change.before===10&&change.after===3));
const favor=structuredClone(state); favor.players.player1.command=2; favor.players.player1.hand=[{instanceId:'favor',cardId:'royal-favor',costModifiers:[]}];
const favored=applyAction(favor,{type:'play-card',handInstanceId:'favor'}); assert(favored.ok,favored.error);
const favorEvent=buildChronicle(favored.state.log,'player1')[0]; assert.equal(favorEvent.icon,'command');
assert(favorEvent.changes.some(change=>change.stat==='Command'&&change.before===2&&change.after===3));
const fight=structuredClone(state); fight.players.player1.board=[unit('attacker','crownlands-champion')]; fight.players.player2.board=[unit('defender','leo-tyrell','player2')];
const fought=applyAction(fight,{type:'military-attack',attackerInstanceId:'attacker',targetUnitInstanceId:'defender'}); assert(fought.ok,fought.error);
const battle=buildChronicle(fought.state.log,'player1')[0]; assert.equal(battle.icon,'military'); assert.match(battle.title,/Crownlands Champion → Leo Tyrell/);
assert(battle.changes.some(change=>change.instanceId==='defender'&&change.stat==='Health'&&change.after===0));
assert(battle.entries.some(entry=>/is destroyed/.test(entry.message)));
const debate=structuredClone(state); debate.players.player1.board=[unit('speaker','grand-counselor')]; debate.players.player2.board=[unit('listener','leo-tyrell','player2')];
const debated=applyAction(debate,{type:'political-attack',attackerInstanceId:'speaker'}); assert(debated.ok,debated.error);
const political=buildChronicle(debated.state.log,'player1')[0]; assert.match(political.title,/Grand Counselor → Leo Tyrell/); assert.match(political.detail,/Political · Victory/);
assert.equal(political.icon,'political');
assert.equal(political.entries[0].chronicle.targetInstanceId,'listener');
assert(political.changes.some(change=>change.stat==='Standing'&&change.after<change.before));
const legacy=[{id:1,turn:7,playerId:'player1',message:'Player 1 begins Turn 4.'},{id:2,turn:7,playerId:'player1',message:'Command refills to 7.'},{id:3,turn:7,playerId:'player2',message:'Drew Blackfyre. (17 cards remain in deck)'},{id:4,turn:7,playerId:'player1',message:'Player 1 ends Turn 4.'}];
const old=buildChronicle(legacy,'player1'); assert.equal(old.length,1); assert.equal(old[0].detail,'Refilled · 7'); assert.equal(old[0].turnOwnerId,'player1');
assert.equal(formatChronicleEntry({id:5,turn:8,message:'Command refills to 8. (2 → 8 Command)'}).detail,'2 → 8');
assert.equal(formatChronicleEntry({id:5,turn:8,message:'Command refills to 8. (6 base + 2 bonus)'}).commandRefill,true);
const privateEntry={id:100,turn:7,playerId:'player2',visibility:'owner',message:'Drew Blackfyre. (17 cards remain in deck)',chronicle:{actionId:1}};
assert(!JSON.stringify(buildChronicle([...played.state.log,privateEntry],'player1')).includes('Blackfyre'));
// Repeated passives only combine within their actual resolution, never across actions.
const passive=(id,actionId)=>({id,turn:7,playerId:'player1',message:"END OF TURN — Highgarden: Verdant Legacy activates. Leo Tyrell gains +1 Influence.",chronicle:{actionId}});
assert.equal(buildChronicle([passive(1,1),passive(2,1),passive(3,3)],'player1').length,2);
assert.equal(formatChronicleEntry({id:1,turn:1,message:'Leo Tyrell recovers 1 Health while Grounded.'}).icon,'heal');
assert.equal(formatChronicleEntry({id:1,turn:1,message:'Leo Tyrell is burned. (12 cards remain in deck)'}).icon,'burned');
assert.equal(formatChronicleEntry({id:1,turn:1,message:'Iron Wrath: Player 1 gains 3 Standing. (20 → 23 Standing)'}).icon,'heal');
assert.equal(formatChronicleEntry({id:1,turn:1,message:'Maelwing becomes Grounded.'}).icon,'grounded');
const fall=structuredClone(state);
fall.players.player1.board=[unit('killer','crownlands-champion')];
fall.players.player2.board=[unit('fall-target','lorent-tyrell','player2')];
fall.players.player2.board[0].currentHealth=1;
fall.players.player2.hand=[]; fall.players.player2.deck=['blackfyre'];
const fallen=applyAction(fall,{type:'military-attack',attackerInstanceId:'killer',targetUnitInstanceId:'fall-target'});
assert(fallen.ok,fallen.error);
assert(fallen.state.log.some(entry=>entry.visibility==='owner'&&entry.playerId==='player2'&&entry.message.includes('Blackfyre')));
const attackerView=projectGameStateForPlayer(fallen.state,'player1');
assert(!JSON.stringify(attackerView.players.player2.hand).includes('blackfyre'));
assert(!JSON.stringify(attackerView.players.player2.deck).includes('blackfyre'));
assert(!JSON.stringify(attackerView.log).includes('Blackfyre'));
assert(!JSON.stringify(buildChronicle(fallen.state.log,'player1')).includes('Blackfyre'));
assert(JSON.stringify(buildChronicle(fallen.state.log,'player2')).includes('Blackfyre'));
const live=structuredClone(state);
live.players.player1.board=[unit('copy-a','leo-tyrell'),unit('copy-b','leo-tyrell')];
live.players.player1.board[0].modifiers=[{id:'buff',strength:3,influence:-1,permanent:true}];
live.players.player1.board[0].currentHealth=1;
const resolved=resolveChronicleEntity(live,'player1',{cardId:'leo-tyrell',instanceId:'copy-a'});
assert.equal(resolved.units[0].instanceId,'copy-a');
assert.equal(chronicleUnitStats(live,resolved.units[0]).strength,getGameCard('leo-tyrell').strength+3);
assert.equal(chronicleUnitStats(live,resolved.units[0]).health,1);
assert.equal(resolveChronicleEntity(live,'player1',{cardId:'leo-tyrell'}).units.length,2);
live.players.player1.board.shift();
assert.equal(resolveChronicleEntity(live,'player1',{cardId:'leo-tyrell',instanceId:'copy-a'}).units.length,0);
live.players.player1.hand=[{instanceId:'hand',cardId:'leo-tyrell',costModifiers:[{id:'discount',amount:-1}]}];
assert.equal(resolveChronicleEntity(live,'player2',{cardId:'leo-tyrell',playerId:'player1'}).hand.length,0);
live.players.player1.board=[];
assert.equal(resolveChronicleEntity(live,'player1',{cardId:'leo-tyrell'}).cost,getGameCard('leo-tyrell').cost-1);
// Projection must retain public metadata while withholding private names.
{
  const projected=projectGameStateForPlayer({...played.state,log:[...played.state.log,privateEntry]},'player1');
  assert(!JSON.stringify(projected.log).includes('Blackfyre'));
}
