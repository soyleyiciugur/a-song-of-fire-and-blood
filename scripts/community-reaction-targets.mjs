import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = name => JSON.parse(fs.readFileSync(path.join(root, 'data', name), 'utf8'));
const forum = read('forum.json');
const chapters = new Map(read('chapters.json').map(c => [c.slug, c.title]));
const threads = new Map(forum.threads.map(t => [t.id, t]));
const quote = value => value == null ? 'null' : `'${String(value).replaceAll("'", "''")}'`;
const title = thread => thread?.chapterSlug ? `${chapters.get(thread.chapterSlug)} — Discussion thread` : thread?.title ?? null;
const targets = [
  ...forum.threads.map(t => ['thread', t.id, `/forum?thread=${t.id}`, t.id, title(t)]),
  ...forum.comments.map(c => ['post', c.id, `/forum?thread=${c.entryId}&comment=${c.id}`, c.entryId, title(threads.get(c.entryId))]),
  ...read('flea-bottom.json').comments.map(c => ['raven', c.id, `/ravens-eye?item=${c.entryId}&comment=${c.id}`, null, null]),
];

// Inspect only literal seed rows in registry INSERT statements, not RPC calls.
const directory = path.join(root, 'supabase', 'migrations');
const registered = new Set();
for (const file of fs.readdirSync(directory).filter(f => f.endsWith('.sql'))) {
  const sql = fs.readFileSync(path.join(directory, file), 'utf8');
  for (const insert of sql.matchAll(/insert into public\.community_reaction_targets\s*\([^;]+?\)\s*values([\s\S]*?);/gi)) {
    for (const row of insert[1].matchAll(/\(\s*'(thread|post|raven)'\s*,\s*'((?:''|[^'])*)'\s*,/g)) {
      registered.add(`${row[1]}:${row[2].replaceAll("''", "'")}`);
    }
  }
}
const missing = targets.filter(([kind, id]) => !registered.has(`${kind}:${id}`));
if (!missing.length) {
  console.log(`Reaction target coverage valid: ${targets.length} repository threads/comments registered in migrations.`);
} else if (process.argv.includes('--write')) {
  let version = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
  // Migration versions must follow the latest checked-in migration even when
  // an earlier migration used a future timestamp.
  const latest = fs.readdirSync(directory).filter(f => /^\d{14}_/.test(f)).sort().at(-1)?.slice(0, 14);
  if (latest && version <= latest) throw new Error(`Clock precedes migration ${latest}; choose a later migration timestamp.`);
  const filename = `${version}_community_reaction_targets.sql`;
  const sql = `begin;\n\n-- Generated by npm run community:reactions. Preserve existing member reactions.\ninsert into public.community_reaction_targets (target_kind,target_id,href,thread_id,thread_title)\nvalues\n${missing.map(row => `  (${row.map(quote).join(',')})`).join(',\n')}\non conflict (target_kind,target_id) do update set\n  href=excluded.href, thread_id=excluded.thread_id, thread_title=excluded.thread_title;\n\ncommit;\n`;
  fs.writeFileSync(path.join(directory, filename), sql);
  console.log(`Prepared ${filename}: ${missing.length} missing targets. Apply with supabase db push --linked before publishing the content.`);
} else {
  console.error(`${missing.length} repository reaction targets are missing from migrations. Run npm run community:reactions, then apply the generated migration with supabase db push --linked.`);
  process.exitCode = 1;
}
